--
-- 设计要点：
--   1. 一张表只回答一个问题，能 join 的不塞字段；
--   2. **没有公司名录表**：企业名录住 CRM / 企业名录 / ATS / 内部主数据，
--      这里只存 class_index_src（去哪个系统、用什么查询式），名录不进库；
--   3. 列表型字段（交付物/KPI/上下游）一条一行，能按值检索、能统计，
--      不是整段 JSON 塞一列；
--   4. 数值型（评分/就绪度）以 TEXT 存，读写统一走 float，
--      避免各库类型差异导致同一份数据在 SQLite/PG 行为不同。
-- ===========================================================================

-- 结构版本与构建溯源：拿到库先知道它是哪版、由什么生成
CREATE TABLE IF NOT EXISTS "schema_version" (
    version           TEXT NOT NULL,
    built_at          TEXT NOT NULL,
    source            TEXT NOT NULL,
    generator         TEXT NOT NULL,
    PRIMARY KEY ("version")
);

-- 类目：钢材加工 / 品牌方 / 用人部门 …（稳定、可复用、可跨行业）
CREATE TABLE IF NOT EXISTS "industry_class" (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              TEXT NOT NULL,
    kind              TEXT NOT NULL,
    label             TEXT,
    is_entity         INTEGER NOT NULL,
    source_file       TEXT NOT NULL,
    UNIQUE ("name")
);

-- 别名：同一个东西的多种叫法收敛到一个 class_name
CREATE TABLE IF NOT EXISTS "class_alias" (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_name        TEXT NOT NULL,
    alias             TEXT NOT NULL,
    source_file       TEXT NOT NULL,
    UNIQUE ("alias"),
    FOREIGN KEY ("class_name") REFERENCES "industry_class"("name")
);

-- 索引源：这个类去哪个系统、用什么查询式查具体公司（只存检索方式）
CREATE TABLE IF NOT EXISTS "class_index_src" (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_name        TEXT NOT NULL,
    source            TEXT NOT NULL,
    query_expr        TEXT NOT NULL,
    FOREIGN KEY ("class_name") REFERENCES "industry_class"("name")
);

-- 岗位引用：哪个岗位的哪个字段引用了什么（类目/接口/岗位三类落点）
CREATE TABLE IF NOT EXISTS "role_chain_ref" (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id           TEXT NOT NULL,
    role_name         TEXT NOT NULL,
    field             TEXT NOT NULL,
    raw_value         TEXT NOT NULL,
    class_name        TEXT NOT NULL,
    ref_kind          TEXT NOT NULL,
    ref_unit          TEXT,
    ref               TEXT,
    ref_index         TEXT,
    ref_note          TEXT
);

-- 行业单元（M2 注册表落库）：一个行业一套岗位
CREATE TABLE IF NOT EXISTS "industry_unit" (
    unit_id           TEXT NOT NULL,
    industry          TEXT NOT NULL,
    industry_alias    TEXT,
    version           TEXT,
    source_file       TEXT,
    PRIMARY KEY ("unit_id")
);

-- 岗位清单（注册表）：岗位 → 前缀 / 触发词 / 简介，是画像卡的事实来源
CREATE TABLE IF NOT EXISTS "industry_role" (
    unit_id           TEXT NOT NULL,
    role_name         TEXT NOT NULL,
    prefix            TEXT,
    description       TEXT,
    keywords          TEXT,
    PRIMARY KEY ("unit_id",
    "role_name"),
    FOREIGN KEY ("unit_id") REFERENCES "industry_unit"("unit_id")
);

-- 岗位画像基线：六维评估的元信息（六维正文分表存）
CREATE TABLE IF NOT EXISTS "role_profile" (
    unit_id           TEXT NOT NULL,
    role_name         TEXT NOT NULL,
    mission           TEXT,
    seniority         TEXT,
    mindset           TEXT,
    tone              TEXT,
    bundle            TEXT,
    install_hint      TEXT,
    scoring_avg       TEXT,
    source_file       TEXT,
    PRIMARY KEY ("unit_id",
    "role_name"),
    FOREIGN KEY ("unit_id") REFERENCES "industry_unit"("unit_id")
);

-- 画像条目：六维里的清单型字段一条一行（deliverables / inputs / kpis …）
CREATE TABLE IF NOT EXISTS "role_profile_item" (
    unit_id           TEXT NOT NULL,
    role_name         TEXT NOT NULL,
    dimension         TEXT NOT NULL,
    field             TEXT NOT NULL,
    value             TEXT NOT NULL,
    position          INTEGER NOT NULL,
    PRIMARY KEY ("unit_id",
    "role_name",
    "dimension",
    "field",
    "position"),
    FOREIGN KEY ("unit_id", "role_name") REFERENCES "role_profile"("unit_id", "role_name")
);

-- 能力评分（0-5 五维）：domain/tooling/judging/execution/comms
CREATE TABLE IF NOT EXISTS "capability_score" (
    unit_id           TEXT NOT NULL,
    role_name         TEXT NOT NULL,
    dimension         TEXT NOT NULL,
    score             TEXT NOT NULL,
    PRIMARY KEY ("unit_id",
    "role_name",
    "dimension"),
    FOREIGN KEY ("unit_id", "role_name") REFERENCES "role_profile"("unit_id", "role_name")
);

-- 工作流：模板 + 岗位覆盖（按步骤 id 合并）
CREATE TABLE IF NOT EXISTS "workflow" (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id           TEXT NOT NULL,
    role_name         TEXT NOT NULL,
    wf_id             TEXT NOT NULL,
    name              TEXT,
    template          TEXT,
    trigger           TEXT,
    handoff_out       TEXT,
    is_default        INTEGER NOT NULL,
    activation_weight TEXT,
    position          INTEGER NOT NULL,
    UNIQUE ("unit_id", "role_name", "wf_id"),
    FOREIGN KEY ("unit_id", "role_name") REFERENCES "role_profile"("unit_id", "role_name")
);

-- 工作流步骤：谁干、按什么 playbook 干、怎么验、用什么 runtime
CREATE TABLE IF NOT EXISTS "workflow_step" (
