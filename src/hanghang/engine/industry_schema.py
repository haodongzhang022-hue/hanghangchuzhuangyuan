def tables(dialect: str = "sqlite") -> List[str]:
    return [t["name"] for t in TABLES]


def columns_of(table: str) -> List[str]:
    for t in TABLES:
        if t["name"] == table:
            return [c[0] for c in t["columns"]]
    raise KeyError(table)


def _col_sql(col: Tuple[str, str, bool], dialect: str) -> str:
    """一列的 DDL 片段。

    `notnull=True` 必须真的渲染成 ``NOT NULL`` —— 早先两个分支都返回空串，
    生成的 DDL 里 NOT NULL 计数为 0。后果不是报错而是**契约不成立**：
    `money_gap.reason` 在库里可以是 NULL，而 validate 要求「有差额不解释不行」；
    `partition.id` 可以为 NULL（SQLite 的非整数主键不拒绝 NULL）。
    """
    name, typ, notnull = col
    base = _TYPES[dialect][typ]
    return f'"{name}" {base}' + (" NOT NULL" if notnull else "")


def ddl(dialect: str = "sqlite") -> str:
    """渲染整份 DDL。两种方言表名列名一致，切库只换这个参数。"""
    if dialect not in _TYPES:
        raise ValueError(f"未知方言 {dialect!r}，可选 {list(_TYPES)}")
    out = []
    for table in TABLES:
        cols = [_col_sql(c, dialect) for c in table["columns"]]
        pk = ", ".join(f'"{c}"' for c in table["pk"])
        cols.append(f"PRIMARY KEY ({pk})")
        for uq in table.get("unique", []):
            cols.append("UNIQUE (" + ", ".join(f'"{c}"' for c in uq) + ")")
        for fk in table.get("fk", []):
            cols.append(f'FOREIGN KEY ("{fk[0]}") REFERENCES "{fk[1]}"("{fk[2]}")')
        out.append(f'CREATE TABLE IF NOT EXISTS "{table["name"]}" (\n  '
                   + ",\n  ".join(cols) + "\n);")
    for name, table, cols in INDEXES:
        out.append(f'CREATE INDEX IF NOT EXISTS "{name}" ON "{table}" ('
                   + ", ".join(f'"{c}"' for c in cols) + ");")
    return "\n\n".join(out) + "\n"


