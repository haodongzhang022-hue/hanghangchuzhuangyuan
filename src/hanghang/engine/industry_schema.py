"""行业分区库的**结构单源**（DDL 双方言 + 与方言无关的数据 SQL）

为什么要有这层：`industry export` 原先在 CLI 里手写了一段 ``CREATE TABLE``，
只有 SQLite 一种方言，列顺序靠 tuple 位置对齐 —— 加一列就要同时改三处
（建表语句、INSERT 的占位符个数、取值顺序），改漏了就静默错位。

这里把「表长什么样」写成一份 ``TABLES``：DDL、INSERT 列表、行数断言全从它派生。
换服务器只换方言参数，表名列名不动。

刻意的取舍：
  · 数据 SQL 只有一份，两种方言共用。标准 ``INSERT ... VALUES`` 两边都认，
    字符串里的单引号按标准翻倍转义即可 —— 为两份数据文件维护两套转义是自找的。
  · 不建视图/触发器/存储过程。跨库麻烦，聚合逻辑留在 Python 与 CSV。
  · 不写公司名录，不写凭据（与 rolecard 的库同一规矩）。
"""
