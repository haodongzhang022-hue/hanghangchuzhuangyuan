def _lit(value) -> str:
    """字面量：字符串按标准翻倍转义，None 落 NULL，布尔落 1/0。

    一份数据 SQL 两种方言都能跑，靠的就是只用标准写法：不用 ``E''``、
    不用 ``\'`` 反斜杠转义（那是 MySQL 的扩展，SQLite 与 PG 都不认）。
    """
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def _int(v):
    """金额落库前转整：元为单位的金额不该带浮点尾巴。

    33 万亿写进 BIGINT 是精确的，但 Python 侧算出来的是 float（`33000000000000.0`）。
    直接入库不会报错，只是导出 SQL 里全是 `.0`，读的人会以为这是估算出来的小数。
    """
    if isinstance(v, float) and v.is_integer():
        return int(v)
    return v


