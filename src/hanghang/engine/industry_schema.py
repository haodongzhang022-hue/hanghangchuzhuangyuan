def tables(dialect: str = "sqlite") -> List[str]:
    return [t["name"] for t in TABLES]


def columns_of(table: str) -> List[str]:
    for t in TABLES:
        if t["name"] == table:
            return [c[0] for c in t["columns"]]
    raise KeyError(table)


def _col_sql(col: Tuple[str, str, bool], dialect: str) -> str:
    name, typ, notnull = col
    base = _TYPES[dialect][typ]
    return f'"{name}" {base}' + ("" if notnull else "")


def ddl(dialect: str = "sqlite") -> str:
    """渲染整份 DDL。两种方言表名列名一致，切库只换这个参数。"""
    if dialect not in _TYPES:
        raise ValueError(f"未知方言 {dialect!r}，可选 {list(_TYPES)}")
    out = []
    for table in TABLES:
        cols = [_col_sql(c, dialect) for c in table["columns"]]
        pk = ", ".join(f'"{c}"' for c in table["pk"])
        cols.append(f"PRIMARY KEY ({pk})")
        for uq in table.get("unique", []):
            cols.append("UNIQUE (" + ", ".join(f'"{c}"' for c in uq) + ")")
        for fk in table.get("fk", []):
            cols.append(f'FOREIGN KEY ("{fk[0]}") REFERENCES "{fk[1]}"("{fk[2]}")')
        out.append(f'CREATE TABLE IF NOT EXISTS "{table["name"]}" (\n  '
                   + ",\n  ".join(cols) + "\n);")
    for name, table, cols in INDEXES:
        out.append(f'CREATE INDEX IF NOT EXISTS "{name}" ON "{table}" ('
                   + ", ".join(f'"{c}"' for c in cols) + ");")
    return "\n\n".join(out) + "\n"


# ---------------------------------------------------------------------------- 数据
def _lit(value) -> str:
    """字面量：字符串按标准翻倍转义，None 落 NULL，布尔落 1/0。

    一份数据 SQL 两种方言都能跑，靠的就是只用标准写法：不用 ``E''``、
    不用 ``\'`` 反斜杠转义（那是 MySQL 的扩展，SQLite 与 PG 都不认）。
    """
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def rows_of(db, snapshot: dict) -> Dict[str, List[tuple]]:
    """把内存里的库 + 计算快照摊成每张表的行（顺序即列顺序）。"""
    rows: Dict[str, List[tuple]] = {t["name"]: [] for t in TABLES}

    meta = {
        "schema_version": SCHEMA_VERSION,
        "data_version": str(snapshot.get("version", "")),
        "data_updated_at": str(snapshot.get("updated_at", "")),
        "generator": "src/hanghang/engine/industry_schema.py",
        "provider_mix_basis": snapshot.get("provider_mix_basis", ""),
        "gdp_note": "gdp_cny 为量级参考，非官方统计；加总只允许同 gdp_kind",
    }
    for k, v in meta.items():
        rows["dataset_meta"].append((k, v))

    for r in snapshot["rows"]:
        mix = r["provider_mix"] or {}
        dec = r.get("provider_mix_declared") or {}
        est = r.get("provider_mix_estimated") or {}
        acc = r.get("access_mix") or {}
        rows["partition"].append((
            r["id"], r["name"], "|".join(r["aliases"]), r["status"],
            r["unit_id"], r["priority"], r["gdp_cny"],
            r.get("gdp_kind", ""), r.get("gdp_confidence", ""),
            r["gdp_scope"], r["gdp_source"],
            mix.get("ai"), mix.get("hybrid"), mix.get("human"),
            dec.get("ai"), dec.get("hybrid"), dec.get("human"),
            est.get("ai"), est.get("hybrid"), est.get("human"),
            acc.get("paid_direct"), acc.get("non_market"),
            acc.get("org_internal"), acc.get("household"),
            r.get("employment"), r["member_count"],
            "|".join(r.get("axes", [])),
            "|".join(f"{k}:{v}" for k, v in (r.get("axis_edges") or {}).items() if v),
            "|".join(r.get("planned_roles", [])),
            "|".join(r["demand_side"]), "|".join(r["cluster_basis"]),
            "|".join(r["channels"]), r["note"],
        ))

    for o in db.occupations:
        gb = db.catalog.gb_code_of(o.get("id", "")) if db.catalog else ""
        entry = db.catalog.entry(gb) if (db.catalog and gb) else None
        rows["occupation"].append((
            o.get("code", ""), o.get("id", ""), o.get("name", ""),
            o.get("deliverable", ""), o.get("provider", ""),
            o.get("billing", ""), db.access_of(o),
            1 if o.get("baseline_occupation") else 0,
            gb, (entry or {}).get("name", ""), o.get("note", ""),
        ))

    for m in db.axis_view.memberships:
        rows["membership"].append((
            m.get("occupation", ""), m.get("partition", ""),
            m.get("axis", ""), m.get("weight", 1.0), m.get("unit_role", ""),
        ))

    if db.catalog is not None:
        for e in db.catalog.occupations:
            rows["gb_catalog"].append((
                e.get("code", ""), e.get("name", ""), e.get("gbm", ""),
                e.get("major", ""), e.get("middle", ""), e.get("minor", ""),
                "|".join(e.get("marks") or []), db.catalog.path_of(e.get("code", "")),
                e.get("desc", ""),
            ))

    # ---- 六口径规模账：缺的口径也占一行，让"隐身"在库里看得见 ----
    scales = getattr(db, "scales", None)
    if scales is not None:
        for p in db.partitions:
            pid = p.get("id", "")
            if not pid:
                continue
            for name in SCALE_METRICS:
                rec = scales.metric(pid, name)
                if rec is None:
                    rows["scale_metric"].append((
                        pid, name, None,
                        "" if name != "employment" else "wan",
                        "", "", "", "",
                        scales.missing_reason(pid, name) or ""))
                    continue
                if name == "employment":
                    value, unit = rec.get("wan"), "wan"
                elif name == "resource":
                    value, unit = rec.get("value"), rec.get("unit", "")
                else:
                    value, unit = rec.get("cny"), "CNY"
                rows["scale_metric"].append((
                    pid, name, value, unit, rec.get("kind", "") or "",
                    rec.get("basis", "") or "", rec.get("source", "") or "",
                    rec.get("confidence", "") or "", ""))

    # ---- 资金流守恒账：节点 / 边 / 差额 ----
    money = getattr(db, "money", None)
    if money is not None:
        for n in money.nodes:
            rows["money_node"].append((
                n.get("id", ""), n.get("type", ""), n.get("sector", "") or "",
                n.get("partition", "") or "", n.get("name", ""),
                n.get("declared_in_cny"), n.get("declared_out_cny"),
                n.get("source", "") or "",
            ))
        for f in money.flows:
            rows["money_flow"].append((
                f.get("from", ""), f.get("to", ""), f.get("kind", ""),
                f.get("amount_cny"), f.get("confidence", "") or "",
                f.get("basis", "") or "",
            ))
        for lk in money.leaks:
            rows["money_gap"].append((
                lk.get("node", ""), "gap", lk.get("side", "") or "",
                lk.get("amount_cny"), lk.get("reason", "") or "",
            ))
        for u in money.unobserved:
            rows["money_gap"].append((
                u.get("node", ""), "unobserved", "",
                None, u.get("reason", "") or u.get("missing", "") or "",
            ))
    return rows


def data_sql(db, snapshot: dict) -> str:
    """与方言无关的数据 SQL（标准 INSERT，SQLite / PostgreSQL 都能直接跑）。"""
    rows = rows_of(db, snapshot)
    out = ["-- 行业分区库数据（与方言无关：标准 INSERT，SQLite / PostgreSQL 通用）",
           "-- 由 src/hanghang/engine/industry_schema.py 生成，请勿手改。"]
    for table in TABLES:                       # 按定义的依赖顺序插入
        name = table["name"]
        cols = ", ".join(f'"{c[0]}"' for c in table["columns"])
        out.append(f"\n-- {name}: {len(rows[name])} 行")
        for row in rows[name]:
            vals = ", ".join(_lit(v) for v in row)
            out.append(f'INSERT INTO "{name}" ({cols}) VALUES ({vals});')
    return "\n".join(out) + "\n"


def counts(db, snapshot: dict) -> Dict[str, int]:
    return {k: len(v) for k, v in rows_of(db, snapshot).items()}
